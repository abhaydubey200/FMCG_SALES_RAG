def d(val):
    """Quantize to 2 decimal places."""
    return float(Decimal(str(val)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


def _get_connection():
    """Get a fresh PostgreSQL connection."""
    import psycopg2
    if not config.USE_POSTGRESQL or not config.DATABASE_URL:
        raise RuntimeError("PostgreSQL required for seeding")
    return psycopg2.connect(config.DATABASE_URL)


def workspace_has_data(workspace_id: str = DEFAULT_WORKSPACE) -> bool:
    """Check if workspace already has structured data assets."""
    try:
        conn = _get_connection()
        try:
            cur = conn.cursor()
            cur.execute(
                "SELECT COUNT(*) FROM assets "
                "WHERE workspace_id = %s AND status = 'ready' AND type = 'structured'",
                (workspace_id,),
            )
            count = cur.fetchone()[0]
            return count > 0
        finally:
            conn.close()
    except Exception:
        return False


def workspace_asset_count(workspace_id: str = DEFAULT_WORKSPACE) -> int:
    """Count structured assets in workspace."""
    try:
        conn = _get_connection()
        try:
            cur = conn.cursor()
            cur.execute(
                "SELECT COUNT(*) FROM assets "
                "WHERE workspace_id = %s AND status = 'ready' AND type = 'structured'",
                (workspace_id,),
            )
            return cur.fetchone()[0]
        finally:
            conn.close()
    except Exception:
        return 0


def kb_has_documents() -> bool:
    """Check if knowledge base documents are indexed."""
    kb_dir = Path(config.KB_DIR)
    if not kb_dir.exists():
        return False
    for doc in KB_DOCS:
        if not (kb_dir / doc).exists():
            return False
    return True


def get_total_revenue(workspace_id: str = DEFAULT_WORKSPACE) -> float:
    """Get current total revenue from workspace data."""
    from src.analytics.dynamic_engine import workspace_total_revenue
    result = workspace_total_revenue(workspace_id)
    return result if result is not None else 0.0


