#!/usr/bin/env python3
"""
QueryBridge — Deterministic Demo Seed Script

Creates the certified demo environment from a clean database:
  - 3 sales datasets (North, South, ERP) with exact revenue totals
  - 5 knowledge base documents for RAG certification
  - Semantic mappings auto-generated by the dynamic engine

DESIGN PRINCIPLES:
  - Deterministic: same CSVs → same revenue every time
  - Idempotent: safe to run repeatedly without double-counting
  - Workspace-aware: seeds into the "default" workspace
  - Verifiable: prints exact values for certification

USAGE:
  python scripts/seed_demo.py               # seed if workspace empty
  python scripts/seed_demo.py --force       # clear + re-seed
  python scripts/seed_demo.py --verify-only # just verify, don't seed

REPRODUCIBILITY:
  After `docker compose down -v && docker compose up -d`, run:
    docker compose exec api python scripts/seed_demo.py
  This restores the complete demo environment.
"""

